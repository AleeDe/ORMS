-- Run as an administrator after migration 3. All accounts and data roll back.
begin;
do $$
declare
  owner uuid:=gen_random_uuid(); member uuid:=gen_random_uuid(); outsider uuid:=gen_random_uuid();
  w1 uuid:=gen_random_uuid(); w2 uuid; personal uuid; extra uuid;
  c1 uuid:=gen_random_uuid(); c2 uuid:=gen_random_uuid(); private_campaign uuid:=gen_random_uuid();
  l1 uuid:=gen_random_uuid(); l2 uuid:=gen_random_uuid(); private_lead uuid:=gen_random_uuid();
  ds uuid:=gen_random_uuid(); task_id uuid:=gen_random_uuid(); activity_id uuid;
  invitation jsonb; old_invitation jsonb; expired_invitation jsonb; scope uuid; actor uuid; rejected boolean; n integer;
begin
  insert into auth.users(id,email,email_confirmed_at,raw_user_meta_data) values
    (owner,owner::text||'@orms-test.invalid',now(),'{}'),(member,member::text||'@orms-test.invalid',now(),'{}'),(outsider,outsider::text||'@orms-test.invalid',now(),'{}');
  insert into public.workspaces(id,owner_id,name) values(w1,owner,'Workspace One');
  perform set_config('request.jwt.claim.sub',owner::text,true);
  perform set_config('request.headers',jsonb_build_object('x-orms-workspace',w1)::text,true);
  execute 'set local role authenticated';
  w2:=public.orms_create_workspace('Workspace Two');
  if w2=owner or w2=w1 then raise exception 'Workspace identity is tied to its owner'; end if;
  if jsonb_array_length(public.orms_workspaces())<>2 then raise exception 'Multiple owned workspaces were not discovered'; end if;
  insert into public.campaigns(id,user_id,name) values(c1,owner,'Same campaign name');
  insert into public.datasets(id,user_id,name) values(ds,owner,'One-only dataset');
  insert into public.leads(id,user_id,dataset_id,business_name) values(l1,owner,ds,'Same business name'),(private_lead,owner,ds,'Private business');
  insert into public.campaigns(id,user_id,name) values(private_campaign,owner,'Private campaign');
  insert into public.campaign_leads(user_id,campaign_id,lead_id) values(owner,c1,l1),(owner,private_campaign,l1),(owner,private_campaign,private_lead);
  insert into public.activities(user_id,lead_id,campaign_id,type,content) values(owner,l1,private_campaign,'NOTE_ADDED','Private history');
  insert into public.settings(user_id,timezone) values(owner,'Asia/Karachi');
  perform public.seed_default_channels();
  insert into public.notifications(user_id,type,title) values(owner,'followup_due','One-only notification');
  perform set_config('request.headers',jsonb_build_object('x-orms-workspace',w2)::text,true);
  if exists(select 1 from public.campaigns) or exists(select 1 from public.leads) or exists(select 1 from public.settings) or exists(select 1 from public.notifications) or exists(select 1 from public.contact_channels) then raise exception 'Sibling workspaces with the same owner leaked data'; end if;
  insert into public.campaigns(id,user_id,name) values(c2,owner,'Same campaign name');
  insert into public.leads(id,user_id,business_name) values(l2,owner,'Same business name');
  insert into public.campaign_leads(user_id,campaign_id,lead_id) values(owner,c2,l2);
  insert into public.settings(user_id,timezone) values(owner,'UTC');
  perform public.seed_default_channels();
  if (select count(*) from public.contact_channels)<>9 then raise exception 'Channel keys conflicted across owned workspaces'; end if;
  if (select count(*) from public.search_leads('Same',20))<>1 then raise exception 'Search crossed workspace boundaries'; end if;
  rejected:=false;
  begin insert into public.activities(user_id,lead_id,campaign_id,type) values(owner,l1,c1,'EMAIL_SENT'); exception when check_violation or insufficient_privilege then rejected:=true; end;
  if not rejected then raise exception 'Cross-workspace campaign write accepted'; end if;
  rejected:=false;
  begin update public.leads set workspace_id=w1 where id=l2; exception when check_violation then rejected:=true; end;
  if not rejected then raise exception 'Owner moved a lead between workspaces'; end if;
  rejected:=false;
  begin
    insert into public.lead_emails(user_id,lead_id,email) values(owner,l1,'cross-workspace@orms-test.invalid');
    set constraints all immediate;
  exception when foreign_key_violation then rejected:=true;
  end;
  if not rejected then raise exception 'A contact was linked to a lead in another workspace'; end if;
  rejected:=false;
  begin perform public.orms_create_invitation(member::text||'@orms-test.invalid',jsonb_build_array(jsonb_build_object('campaign_id',c1,'role','manager'))); exception when raise_exception then rejected:=true; end;
  if not rejected then raise exception 'Invitation included a campaign from a sibling workspace'; end if;
  perform set_config('request.headers',jsonb_build_object('x-orms-workspace',w1)::text,true);
  expired_invitation:=public.orms_create_invitation(outsider::text||'@orms-test.invalid',jsonb_build_array(jsonb_build_object('campaign_id',c1,'role','viewer')));
  execute 'reset role';
  update auth.users set email_confirmed_at=null where id=outsider;
  execute 'set local role authenticated';
  perform set_config('request.jwt.claim.sub',outsider::text,true);
  rejected:=false;
  begin perform public.orms_accept_invitation(expired_invitation->>'token'); exception when raise_exception then rejected:=true; end;
  if not rejected then raise exception 'Unverified email accepted an invitation'; end if;
  execute 'reset role';
  update auth.users set email_confirmed_at=now() where id=outsider;
  update public.team_invitations set expires_at=now()-interval '1 second' where id=(expired_invitation->>'id')::uuid;
  execute 'set local role authenticated';
  rejected:=false;
  begin perform public.orms_accept_invitation(expired_invitation->>'token'); exception when raise_exception then rejected:=true; end;
  if not rejected or public.orms_invitation_preview(expired_invitation->>'token') is not null then raise exception 'Expired invitation remained usable'; end if;
  perform set_config('request.jwt.claim.sub',owner::text,true);
  old_invitation:=public.orms_create_invitation(member::text||'@orms-test.invalid',jsonb_build_array(jsonb_build_object('campaign_id',c1,'role','member')));
  invitation:=public.orms_create_invitation(member::text||'@orms-test.invalid',jsonb_build_array(jsonb_build_object('campaign_id',c1,'role','member')));
  if public.orms_invitation_preview(old_invitation->>'token') is not null then raise exception 'Replacing an invitation left the old token active'; end if;
  if public.orms_invitation_preview(invitation->>'token')->>'workspace_name'<>'Workspace One' then raise exception 'Invitation preview omitted the workspace'; end if;
  perform set_config('request.jwt.claim.sub',outsider::text,true);
  rejected:=false;
  begin perform public.orms_accept_invitation(invitation->>'token'); exception when raise_exception then rejected:=true; end;
  if not rejected then raise exception 'Wrong email accepted invitation'; end if;
  perform set_config('request.jwt.claim.sub',member::text,true);
  personal:=public.orms_create_workspace('Member personal workspace');
  scope:=public.orms_accept_invitation(invitation->>'token');
  if scope<>w1 or jsonb_array_length(public.orms_workspaces())<>2 then raise exception 'Existing account lost its personal workspace on joining'; end if;
  if (select count(*) from public.campaigns)<>1 or (select count(*) from public.leads)<>1 or exists(select 1 from public.activities) then raise exception 'Member leaked private campaigns or library history'; end if;
  extra:=public.orms_create_workspace('Another independent workspace');
  if extra=personal or jsonb_array_length(public.orms_workspaces())<>3 then raise exception 'Invited member could not create another owned workspace'; end if;
  insert into public.activities(user_id,lead_id,campaign_id,type,actor_id) values(member,l1,c1,'EMAIL_SENT',owner) returning actor_id,workspace_id,id into actor,scope,activity_id;
  if actor<>member or scope<>w1 then raise exception 'Outreach attribution or workspace was lost'; end if;
  insert into public.tasks(id,user_id,lead_id,campaign_id,title,due_date) values(task_id,member,l1,c1,'Member task',current_date);
  update public.tasks set status='completed' where id=task_id;
  if not exists(select 1 from public.tasks where id=task_id and completed_by=member) then raise exception 'Completion attribution was lost'; end if;
  perform set_config('request.headers',jsonb_build_object('x-orms-workspace',personal)::text,true);
  if exists(select 1 from public.campaigns) or exists(select 1 from public.tasks) or exists(select 1 from public.activities) then raise exception 'Joined company data appeared in a personal workspace'; end if;
  perform set_config('request.headers',jsonb_build_object('x-orms-workspace',w2)::text,true);
  if public.orms_current_workspace() is not null or exists(select 1 from public.campaigns) then raise exception 'Forged workspace scope granted access'; end if;
  perform set_config('request.headers','{"x-orms-workspace":"invalid"}',true);
  if public.orms_current_workspace() is not null then raise exception 'Malformed scope did not fail closed'; end if;
  perform set_config('request.jwt.claim.sub',owner::text,true);
  perform set_config('request.headers',jsonb_build_object('x-orms-workspace',w2)::text,true);
  invitation:=public.orms_create_invitation(member::text||'@orms-test.invalid',jsonb_build_array(jsonb_build_object('campaign_id',c2,'role','viewer')));
  perform set_config('request.jwt.claim.sub',member::text,true);
  perform public.orms_accept_invitation(invitation->>'token');
  if public.orms_campaign_role(c2)<>'viewer' then raise exception 'Role from another workspace carried over'; end if;
  update public.campaign_leads set status='won' where campaign_id=c2;
  get diagnostics n=row_count;
  if n<>0 then raise exception 'Viewer changed progress'; end if;
  perform set_config('request.jwt.claim.sub',owner::text,true);
  perform set_config('request.headers',jsonb_build_object('x-orms-workspace',w1)::text,true);
  invitation:=public.orms_create_invitation(member::text||'@orms-test.invalid',jsonb_build_array(jsonb_build_object('campaign_id',c1,'role','manager')));
  perform public.orms_remove_member(member);
  perform set_config('request.jwt.claim.sub',member::text,true);
  if public.orms_current_workspace() is not null or exists(select 1 from public.tasks) then raise exception 'Revoked member retained company access'; end if;
  rejected:=false;
  begin perform public.orms_accept_invitation(invitation->>'token'); exception when raise_exception then rejected:=true; end;
  if not rejected then raise exception 'A pending invite restored revoked membership'; end if;
  perform set_config('request.headers',jsonb_build_object('x-orms-workspace',w2)::text,true);
  if public.orms_campaign_role(c2)<>'viewer' then raise exception 'Removal from one company removed another company membership'; end if;
  execute 'reset role';
  if not exists(select 1 from public.activities where id=activity_id and actor_id=member and workspace_id=w1) then raise exception 'Removal deleted outreach history'; end if;
  set constraints all immediate;
end;
$$;
rollback;
